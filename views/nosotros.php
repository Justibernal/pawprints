      <h2 id="historia-heading">Nuestra historia</h2>
      <p>
        PawPrints nació en 2010 como un pequeño local de barrio en Luján, con la idea
        de que cualquier persona pudiera encontrar un libro que la representara.
        Con el tiempo, y gracias a la comunidad de lectores que nos acompañó, fuimos
        creciendo hasta convertirnos en una librería de referencia de la zona,
        sumando también la venta online para llegar a más gente.
      </p>

